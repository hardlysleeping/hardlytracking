import '../../src/app.css';
import { viewport } from '../../src/lib/layout.svelte';
viewport.start();
import { mount, unmount } from 'svelte';
import Library from '../../src/views/Library.svelte';
import Search from '../../src/views/Search.svelte';
import { library } from '../../src/state/library.svelte';
import { settings } from '../../src/state/settings.svelte';
import { categories } from '../../src/state/categories.svelte';
import { downloads } from '../../src/state/downloads.svelte';
import { memoryDatabase } from '../../src/lib/db/open';
import { LibraryStore } from '../../src/lib/db/store';
const store = new LibraryStore(memoryDatabase());
const saved = JSON.parse(sessionStorage.getItem('browse-fixture-settings') || '{}');
for (const [key,value] of Object.entries(saved)) await store.setPref(`settings.${key}`,value);
await settings.load(store);
settings.set('showContinue', false);
const cover = 'data:image/svg+xml,' + encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="200" height="300"><rect width="200" height="300" fill="#346579"/><circle cx="100" cy="120" r="65" fill="#98b6a3"/><text x="20" y="240" fill="white" font-size="30">QA COVER</text></svg>');
const items = Array.from({length:18},(_,i)=>({ id:`archive:${i}`,provider:'archive',title:`Fixture ${String(i).padStart(2,'0')} — A long comic title`,author:'Author name',status:'ongoing',description:'A useful cover and details distinguish Card browsing from a compact cover grid and a horizontal metadata row.',cover,categoryIds:['qa-category'] }));
for (const item of items) { await store.addSeries(item); }
await store.database.put('viewState',{key:'all',collectionId:'all',view:'list',coverSize:196,at:1});
await store.database.put('books',{seriesId:'archive:0',chapterId:'archive:0:1',name:'fixture.cbz',bytes:1048576,pageCount:20,kind:'cbz',blob:new Blob(),addedAt:0});
const provider = {kind:'archive',search:async()=>({items,hasNext:false}), details:async(id)=>items.find(x=>x.id===id),chapters:async()=>[],sources:async()=>[]};
library.profile = {store,providers:[provider]};
library.sources = [{id:'archive:source',provider:'archive',name:'QA source',lang:'en'}];
library.library = items;
library.ready = true;
categories.items = [{id:'qa-category',name:'Long fixture collection name',hidden:false,pinned:false,order:0}];
let app;
window.qa = {viewport,settings,store,library,items, async screen(name) {if(app) await unmount(app); app = mount(name==='Library'?Library:Search,{target:document.querySelector('#qa'),props:name==='Search'?{initial:'fixture'}:{}});}, persist(){const keys=['libraryView','browseColumns','browseDensity'];sessionStorage.setItem('browse-fixture-settings',JSON.stringify(Object.fromEntries(keys.map(k=>[k,settings[k]]))));}};
await window.qa.screen(new URLSearchParams(location.search).get('screen') || 'Library');
